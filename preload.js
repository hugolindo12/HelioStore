const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('helio', {
  win: {
    minimize: () => ipcRenderer.invoke('win:minimize'),
    maximize: () => ipcRenderer.invoke('win:maximize'),
    close: () => ipcRenderer.invoke('win:close'),
    onState: (cb) => ipcRenderer.on('win:state', (_, s) => cb(s)),
  },
  catalog: () => ipcRenderer.invoke('catalog:get'),
  state: () => ipcRenderer.invoke('state:get'),
  settings: {
    set: (patch) => ipcRenderer.invoke('settings:set', patch),
    pickDir: () => ipcRenderer.invoke('settings:pickDir'),
    pickCatalog: () => ipcRenderer.invoke('settings:pickCatalog'),
  },
  install: (info) => ipcRenderer.invoke('app:install', info),
  cancel: (id) => ipcRenderer.invoke('app:cancel', id),
  uninstall: (id) => ipcRenderer.invoke('app:uninstall', id),
  rollback: (id) => ipcRenderer.invoke('app:rollback', id),
  translate: (lang, texts) => ipcRenderer.invoke('i18n:translate', lang, texts),
  sizes: () => ipcRenderer.invoke('app:sizes'),
  account: {
    get: () => ipcRenderer.invoke('account:get'),
    loginToken: (t) => ipcRenderer.invoke('account:login-token', t),
    loginDevice: () => ipcRenderer.invoke('account:login-device'),
    cancel: () => ipcRenderer.invoke('account:cancel'),
    logout: () => ipcRenderer.invoke('account:logout'),
    repos: () => ipcRenderer.invoke('account:repos'),
    onChanged: (cb) => ipcRenderer.on('account:changed', (_, p) => cb(p)),
  },
  self: {
    get: () => ipcRenderer.invoke('self:get'),
    check: () => ipcRenderer.invoke('self:check'),
    install: () => ipcRenderer.invoke('self:install'),
    onChanged: (cb) => ipcRenderer.on('self:changed', (_, p) => cb(p)),
  },
  launch: (id) => ipcRenderer.invoke('app:launch', id),
  shortcut: (id, where, on) => ipcRenderer.invoke('shortcut:set', id, where, on),
  openFolder: (id) => ipcRenderer.invoke('app:openFolder', id),
  openExternal: (url) => ipcRenderer.invoke('shell:open', url),
  onProgress: (cb) => ipcRenderer.on('install:progress', (_, p) => cb(p)),
  // Dock flutuante (2º plano)
  github: {
    add: (input) => ipcRenderer.invoke('github:add', input),
    inspect: (input) => ipcRenderer.invoke('github:inspect', input),
    remove: (id) => ipcRenderer.invoke('github:remove', id),
    override: (id, patch) => ipcRenderer.invoke('github:override', id, patch),
    check: () => ipcRenderer.invoke('github:check'),
    stats: (repo) => ipcRenderer.invoke('github:stats', repo),
  },
  onStateChanged: (cb) => ipcRenderer.on('state:changed', () => cb()),
  onCatalogChanged: (cb) => ipcRenderer.on('catalog:changed', (_, p) => cb(p)),
  clipboardRead: () => ipcRenderer.invoke('clipboard:read'),
  running: () => ipcRenderer.invoke('running:get'),
  onRunning: (cb) => ipcRenderer.on('running:changed', (_, ids) => cb(ids)),
  quitApp: (id) => ipcRenderer.invoke('app:quit', id),
  dockMenu: (id) => ipcRenderer.invoke('dock:menu', id),
  dockIgnore: (v) => ipcRenderer.invoke('dock:ignoreMouse', v),
  openStore: () => ipcRenderer.invoke('dock:openStore'),
  dockFit: (w, h) => ipcRenderer.invoke('dock:fit', { w, h }),
  onDockRefresh: (cb) => ipcRenderer.on('dock:refresh', () => cb()),
});
